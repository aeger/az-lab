def write_heartbeat(status="active", metadata=None):
    """Write task_poller heartbeat to agent_heartbeat table."""
    try:
        payload = json.dumps({
            "agent": "task_poller",
            "status": status,
            "last_heartbeat": datetime.now(timezone.utc).isoformat(),
            "metadata": metadata or {"host": HOSTNAME},
        }).encode()
        req = urllib.request.Request(
            f"{SUPABASE_URL}/rest/v1/agent_heartbeat?on_conflict=agent",
            data=payload,
            method="POST",
            headers={
                "apikey": SUPABASE_KEY,
                "Authorization": f"Bearer {SUPABASE_KEY}",
                "Content-Type": "application/json",
                "Prefer": "resolution=merge-duplicates",
            }
        )
        urllib.request.urlopen(req, timeout=10)
    except Exception as e:
        # Never raise — callers depend on the heartbeat being unable to break a
        # run. But do not swallow silently either: a heartbeat that cannot leave
        # the network is exactly what trips a `silent_agent` kill switch, and a
        # bare `except: pass` leaves no trace, so every incident has to be
        # reconstructed from cloudflared/gluetun timings (2026-08-22, 2026-09-02,
        # 2026-09-04). sage.py/argus.py already log this; match them. No streak
        # counter here — the poller is a oneshot, so state dies with the process.
        print(f"[poller] HEARTBEAT FAILED — {type(e).__name__}: {e}. "
              f"Silence from here will look like a silent_agent anomaly; "
              f"suspect network/WAN before suspecting the poller.", file=sys.stderr)


# ── JeffLoop: auto-detect tasks needing Jeff input ────────────────────────────

_JEFF_INPUT_KEYWORDS = [
    "@jeff",
    "need your input", "need your decision", "need your approval", "need your confirmation",
    "need jeff", "needs jeff",
    "your choice", "your call", "your decision", "your approval",
    "please advise", "please confirm", "please approve", "please choose", "please decide",
    "waiting for you", "waiting for jeff", "up to you", "your preference",
    "decision point", "requires your", "require your",
]

_JEFF_QUESTION_RE = re.compile(
    r"\b("
    r"should (i|we|claude)\b|"
    r"do you (want|prefer|need|approve)\b|"
    r"would you (like|prefer|want)\b|"
    r"which (one|option|approach|method|path|direction)\b|"
    r"can you (confirm|approve|choose|decide)\b"
    r")",
    re.IGNORECASE,
)


def _needs_jeff_input(text: str) -> tuple[bool, str]:
    """Scan task result for signals that Jeff input is needed.
    Returns (True, reason_snippet) or (False, '').
    """
    if not text:
        return False, ""
    lower = text.lower()
    for kw in _JEFF_INPUT_KEYWORDS:
        if kw in lower:
            idx = lower.index(kw)
            snippet = text[max(0, idx - 20): idx + len(kw) + 60].strip()
            return True, snippet
    m = _JEFF_QUESTION_RE.search(text)
    if m:
        snippet = text[max(0, m.start() - 20): m.end() + 60].strip()
        return True, snippet
    return False, ""


def _notify_summary(result: str, max_chars: int = 600) -> str:
    """Short Discord summary of a task result.

    Was `result.splitlines()[0][:120]`, which silently dropped everything after
    the first line — a result listing several follow-ups showed up as one. Keep
    the leading paragraph instead, and say so when there is more to read.
    """
    if not result:
        return "done"
    text = result.strip()
    # Leading paragraph, not just the first line.
    para = text.split("\n\n", 1)[0].strip()
    clipped = len(para) < len(text)
    if len(para) > max_chars:
        para = para[:max_chars].rstrip()
        clipped = True
    return para + ("\n… (full result in the task row)" if clipped else "")


def mark_pending_jeff_action(task_id: str, result: str, reason: str, title: str = "", goal_id: str | None = None) -> None:
    """Transition task to pending_jeff_action and notify Jeff via Discord."""
    # The row is the full text — do not clip it to _RESULT_MAX_CHARS and then
    # point at "the task row" for the rest, because this IS the task row and the
    # tail is gone the moment this process exits. Only the runaway cap applies.
    stored_result = result
    if result and len(result) > _JEFF_RESULT_MAX_CHARS:
        stored_result = result[:_JEFF_RESULT_MAX_CHARS] + (
            f"\n... [truncated from {len(result)} chars — remainder not retained]"
        )
    api_request(
        "PATCH",
        f"task_queue?id=eq.{task_id}",
        data={"status": "pending_jeff_action", "result": stored_result},
    )
    log_activity("status", f"Pending Jeff action: {reason[:100]}", task_id=task_id)
    display = title or task_id
    # Send the FULL result body, not just the signal snippet. Jeff reads this in
    # Discord and acts on it — if the agent asked for three things, he has to see
    # all three. notify.send() splits anything over Discord's 2000-char cap into
    # numbered parts, so a long body is delivered whole rather than clipped.
    body = (stored_result or "").strip()
    discord_notify(
        f"🙋 **Jeff input needed:** {display}\n"
        f"**Signal:** `{reason[:120]}`\n"
        + (f"\n{body}\n" if body else "")
        + "\nSet task status back to `ready` once you've provided direction."
    )
    print(f"Task {task_id} transitioned to pending_jeff_action.")


def recover_stuck_tasks():
    """Reset tasks stuck in claimed/in_progress_agent for >30 min with no recent agent_activity."""
    from datetime import timedelta
    try:
        cutoff_time = datetime.now(timezone.utc) - timedelta(minutes=30)
        cutoff_activity = datetime.now(timezone.utc) - timedelta(minutes=10)

        # Query all in-flight rows; filter in Python to handle NULL claimed_at.
        # The authoritative age signal is COALESCE(claimed_at, updated_at, created_at).
        all_inflight = api_request(
            "GET",
            "task_queue",
            params={
                "status": "in.(claimed,in_progress_agent)",
                "archived_at": "is.null",
                "select": "id,title,status,claimed_at,updated_at,created_at",
                "limit": "100",
            },
        )
        if not all_inflight:
            return

        stuck = []
        for task in all_inflight:
            # Use COALESCE logic: claimed_at → updated_at → created_at
            age_ts = task.get("claimed_at") or task.get("updated_at") or task.get("created_at")
            if not age_ts:
                continue
            # _parse_iso, not a hand-rolled strip: replace("+00","") turns the
            # "+00:00" PostgREST returns into a trailing ":00" and fromisoformat
            # rejects it, which killed the whole sweep.
            age = _parse_iso(age_ts)
            if age.tzinfo is None:
                age = age.replace(tzinfo=timezone.utc)
            if age < cutoff_time:
                stuck.append(task)

        if not stuck:
            return

        recovered = []
        for task in stuck:
            task_id = task["id"]
            # Check for recent agent_activity on this task
            recent = api_request(
                "GET",
                "agent_activity",
                params={
                    "task_id": f"eq.{task_id}",
                    "created_at": f"gt.{cutoff_activity.isoformat()}",
                    "select": "id",
                    "limit": "1",
                },
            )
            if recent:
                continue  # still alive — skip

            # No recent activity → reset to ready
            api_request(
                "PATCH",
                f"task_queue?id=eq.{task_id}",
                data={"status": "ready", "claimed_by": None, "claimed_at": None},
            )
            log_activity("status", f"Auto-recovered stuck task → ready", task_id=task_id)
            recovered.append(task["title"])
            print(f"Recovered stuck task {task_id}: {task['title']}")

        if recovered:
            titles = ", ".join(recovered[:3])
            extra = f" (+{len(recovered) - 3} more)" if len(recovered) > 3 else ""
            discord_notify(
                f"♻️ **Stuck task recovery:** {len(recovered)} task(s) reset to ready\n"
                f"{titles}{extra}"
            )
    except Exception as e:
        print(f"recover_stuck_tasks failed (non-fatal): {e}", file=sys.stderr)


# ── Staleness sweep ──────────────────────────────────────────────────────────
# Nothing in the system ever looked at old rows. Two Discord-delivery tasks sat at
# status='ready' since 2026-04-30 — 103 days — because 'ready' is a perfectly healthy
# status and no report ever aggregated by age. Same for pending_jeff_action, which is
# a dead end unless Jeff happens to remember it, and for terminal 'failed'.
#
# The sweep is deliberately notify-only: it does NOT requeue or reopen anything. A row
# that has been stale for 100 days is stale for a reason, and auto-retrying it here
# would fight the retry logic in mark_failed. Surfacing it is the whole job.
STALE_NOTIFIED_FILE = os.path.expanduser("~/.claude-queue/stale_notified.json")
STALE_AFTER_DAYS = _env_int("STALE_AFTER_DAYS", 7)
STALE_RENOTIFY_DAYS = _env_int("STALE_RENOTIFY_DAYS", 7)  # re-ping cadence per task
# 'claimed'/'in_progress_agent' are deliberately absent — recover_stuck_tasks already
# owns those and resets them after 30 min. 'pending_eval' is included because a row
# waiting on Iris rots exactly like one waiting on Jeff.
STALE_SWEEP_STATUSES = ("ready", "failed", "pending_jeff_action", "pending_eval")
_STALE_MAX_LISTED = 10


def _load_stale_notified() -> dict:
    try:
        with open(STALE_NOTIFIED_FILE) as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def _save_stale_notified(state: dict) -> None:
    try:
        os.makedirs(os.path.dirname(STALE_NOTIFIED_FILE), exist_ok=True)
        with open(STALE_NOTIFIED_FILE, "w") as f:
            json.dump(state, f)
    except Exception as e:
        print(f"_save_stale_notified failed (non-fatal): {e}", file=sys.stderr)


def sweep_stale_tasks():
    """Surface tasks rotting in ready/failed/pending_jeff_action to Discord.

    Runs on every 5-min poll but only *speaks* when a task has not been reported in
    STALE_RENOTIFY_DAYS — otherwise it would post the same seven rows 288 times a day
    and get muted within a week, which is exactly how the queue went blind in the
    first place. Best-effort: never raises, never blocks the poll.
    """
    try:
        cutoff = (datetime.now(timezone.utc) - timedelta(days=STALE_AFTER_DAYS)).isoformat()
        rows = api_request(
            "GET",
            "task_queue",
            params={
                "status": f"in.({','.join(STALE_SWEEP_STATUSES)})",
                "created_at": f"lt.{cutoff}",
                "order": "created_at.asc",
                "limit": "50",
                "select": "id,title,status,priority,target,attempt_count,created_at,tags",
            },
        )
    except Exception as e:
        print(f"sweep_stale_tasks fetch failed (non-fatal): {e}", file=sys.stderr)
        return

    rows = [r for r in (rows or []) if not _is_internal_housekeeping(r)]
    state = _load_stale_notified()
    now = datetime.now(timezone.utc)

    # Drop bookkeeping for rows that are no longer stale, so a task that goes stale
    # again months later gets reported immediately instead of being silently suppressed.
    live_ids = {r["id"] for r in rows}
    state = {k: v for k, v in state.items() if k in live_ids}

    due = []
    for r in rows:
        last = state.get(r["id"])
        if last:
            try:
                if (now - datetime.fromisoformat(last)).days < STALE_RENOTIFY_DAYS:
                    continue
            except ValueError:
                pass  # unparseable timestamp — treat as never notified
        due.append(r)

    if not due:
        _save_stale_notified(state)
        return

    def _age_days(row):
        try:
            created = datetime.fromisoformat(row["created_at"].replace("Z", "+00:00"))
            return (now - created).days
        except Exception:
            return 0

    due.sort(key=_age_days, reverse=True)
    lines = [
        f"• `{r['status']}` **{(r.get('title') or r['id'][:8])[:70]}** "
        f"— {_age_days(r)}d old, P{r.get('priority', '?')}, "
        f"{r.get('attempt_count') or 0} attempt(s), `{r['id'][:8]}`"
        for r in due[:_STALE_MAX_LISTED]
    ]
    overflow = len(due) - len(lines)
    if overflow > 0:
        lines.append(f"• …and {overflow} more (query task_queue for the full list)")

    discord_notify(
        f"🧹 **Stale queue sweep — {len(due)} task(s) idle >{STALE_AFTER_DAYS}d:**\n"
        + "\n".join(lines)
        + f"\nNothing was requeued. Re-reported every {STALE_RENOTIFY_DAYS}d until resolved."
    )
    print(f"sweep_stale_tasks: reported {len(due)} stale task(s).")
    log_activity("status", f"Stale sweep: {len(due)} task(s) idle >{STALE_AFTER_DAYS}d")

    for r in due:
        state[r["id"]] = now.isoformat()
    _save_stale_notified(state)


# ── Waiting-gate release sweep (migration 136) ───────────────────────────────
# `waiting` is the first-class "gated and healthy" status: not claimable, not
# failed, not Jeff's problem. This sweep is the ONLY thing that releases it, by
# evaluating the row's machine-checkable gate every poll:
#   not_before                                  — time gate (also enforced at claim)
#   unblock_condition {"type":"tasks_complete"} — listed tasks completed/archived
#   unblock_condition {"type":"file_newer_than"}— local file mtime newer than `after`
#   blocked_by_task_ids                         — implicit tasks_complete gate
# All declared gates must pass. A condition the sweep cannot evaluate (unknown
# type, missing file, bad timestamp) never releases — a wrongly-held task is a
# visible `waiting_overdue`/`waiting_no_gate` finding in task_queue_health,
# while a wrongly-released one burns attempts on data that does not exist yet
# (the ff8c500d failure mode this replaces).

def _parse_iso(ts: str) -> datetime:
    return datetime.fromisoformat(str(ts).replace("Z", "+00:00"))


def _gate_state(task: dict) -> tuple[bool, str]:
    """(passed, detail) for a waiting task's release gate."""
    now = datetime.now(timezone.utc)
    passed_checks = []

    nb = task.get("not_before")
    if nb:
        try:
            if _parse_iso(nb) > now:
                return False, f"not_before {nb} not reached"
        except ValueError:
            return False, f"unparseable not_before {nb!r}"
        passed_checks.append(f"not_before {nb} passed")

    cond = task.get("unblock_condition")
    if cond is not None and not isinstance(cond, dict):
        return False, "unblock_condition is not an object"
    ctype = (cond or {}).get("type")

    if ctype == "time":
        if not nb:
            return False, "gate type=time but not_before is unset"
    elif ctype == "tasks_complete":
        ids = [str(x) for x in (cond.get("task_ids") or []) if x]
        if not ids:
            return False, "gate type=tasks_complete with no task_ids"
        missing = _dependencies_incomplete({"blocked_by_task_ids": ids})
        if missing:
            return False, f"{len(missing)}/{len(ids)} gate task(s) incomplete"
        passed_checks.append(f"all {len(ids)} gate task(s) complete")
    elif ctype == "file_newer_than":
        path = os.path.expanduser(str(cond.get("path") or ""))
        after = cond.get("after")
        if not path or not after:
            return False, "gate type=file_newer_than needs both path and after"
        try:
            mtime = datetime.fromtimestamp(os.path.getmtime(path), tz=timezone.utc)
        except OSError as e:
            return False, f"cannot stat {path}: {e}"
        try:
            if mtime <= _parse_iso(after):
                return False, f"{path} not modified since {after}"
        except ValueError:
            return False, f"unparseable after {after!r}"
        passed_checks.append(f"{path} modified {mtime.strftime('%Y-%m-%dT%H:%M:%SZ')} > {after}")
    elif ctype is not None:
        return False, f"unknown gate type {ctype!r}"

    dep_missing = _dependencies_incomplete(task)
    dep_ids = task.get("blocked_by_task_ids") or []
    if dep_missing:
        return False, f"{len(dep_missing)}/{len(dep_ids)} dependenc(ies) incomplete"
    if dep_ids:
        passed_checks.append(f"all {len(dep_ids)} dependenc(ies) complete")

    if not passed_checks:
        # No gate declared at all — nothing will ever legitimately release this.
        # Surfaced as waiting_no_gate by task_queue_health; a human decides.
        return False, "no gate declared (waiting_no_gate)"
    return True, "; ".join(passed_checks)


def sweep_waiting_tasks():
    """Flip waiting→ready for every task whose gate has opened. Best-effort."""
    try:
        rows = api_request("GET", "task_queue", params={
            "status": "eq.waiting",
            "select": "id,title,target,not_before,unblock_condition,blocked_by_task_ids",
            "order": "created_at.asc",
            "limit": "50",
        }) or []
    except Exception as e:
        print(f"sweep_waiting_tasks fetch failed (non-fatal): {e}", file=sys.stderr)
        return

    for t in rows:
        try:
            passed, detail = _gate_state(t)
        except Exception as e:
            print(f"gate evaluation failed for {t['id']} (held): {e}", file=sys.stderr)
            continue
        if not passed:
            continue
        try:
            # Status-guarded like the claim path, so a row a human just moved is
            # left alone. blocked_reason is cleared — it described the gate.
            released = api_request(
                "PATCH",
                f"task_queue?id=eq.{t['id']}&status=eq.waiting",
                data={"status": "ready", "blocked_reason": None},
            )
        except Exception as e:
            print(f"sweep_waiting_tasks release failed for {t['id']} (non-fatal): {e}", file=sys.stderr)
            continue
        if not released:
            continue
        title = t.get("title") or t["id"][:8]
        print(f"Gate released: {t['id']} ({detail})")
        log_activity("status", f"Gate released → ready: {detail}", task_id=t["id"])
        discord_notify(f"⏰ **Gate released:** {title}\n{detail} — task is now `ready`.")


# The zombie-row probe that briefly lived here was moved to anomaly-heartbeat's
# check_zombie_tasks() (migration 143's task_queue_zombies view). Three reasons:
# it false-positived on every freshly claimed row (a task claimed 1min ago has no
# activity in the 30min window), it issued one HTTP request per in-flight row, and
# it reposted to Discord every 5min with no change-only gating. The heartbeat
# already owns anomaly dedup and record_anomaly.


def main():
    print(f"[{datetime.now().isoformat()}] Polling task queue on {HOSTNAME}...")

    # Liveness FIRST. This used to sit after the five sweeps below, which meant a
    # transient Supabase timeout in any of them killed the process before the
    # heartbeat was written — the poller was alive and on schedule, but looked
    # silent. Three such runs in a row tripped the silent_agent kill switch on
    # 2026-09-04. The heartbeat reports "this process ran", so it must not be
    # gated behind the work whose failure it is supposed to survive.
    # write_heartbeat() swallows its own exceptions, so this cannot break main().
    write_heartbeat("active")

    # Auto-recover tasks stuck in claimed/in_progress_agent
    recover_stuck_tasks()

    # Route any unclassified tasks first
    route_auto_tasks()

    # Ping Discord if cowork tasks are pending
    notify_cowork_tasks()

    # Surface rows rotting in ready/failed/pending_jeff_action
    sweep_stale_tasks()

    # Release waiting tasks whose time/data gate has opened
    sweep_waiting_tasks()

    write_heartbeat("active")

    task = claim_next_task()
    if not task:
        print("No pending tasks.")
        # Try to auto-queue from goals backlog
        auto_queue_from_goals()
        return

    task_id = task["id"]
    title = task["title"]
    print(f"Claimed task {task_id}: {title}")

    housekeeping = _is_internal_housekeeping(task)

    mark_in_progress(task_id)
    stamp_task_skill(task)  # attribute the task to a skill before work starts
    log_activity("status", f"Claimed: {title}", task_id=task_id)
    if not housekeeping:  # transcript handoffs are silent plumbing — don't ping Jeff
        discord_notify(f"🟡 Claimed: {title} — starting now")
    episode_id = start_episode(task)

    try:
        model = route_task(task)
        prompt = build_prompt(task)
        model_label = model or "sonnet (default)"
        print(f"Running claude ({model_label}) for task: {title}")
        log_activity("thinking", f"Starting: {title} [model: {model_label}]", task_id=task_id)
        task_ctx = task.get("context") or {}
        task_timeout = task_ctx.get("timeout_secs") if isinstance(task_ctx, dict) else None
        result = run_claude(prompt, task_id=task_id, model=model, timeout=task_timeout)
        summary = _notify_summary(result)
        goal_id = task.get("goal_id")

        # JeffLoop: auto-detect if result signals Jeff input is needed.
        # Skip for housekeeping: a transcript handoff often echoes Jeff's own
        # words (e.g. "why are these sent to me?") and would false-escalate to him.
        jeff_needed, jeff_reason = (False, "") if housekeeping else _needs_jeff_input(result)
        if jeff_needed:
            mark_pending_jeff_action(task_id, result, jeff_reason, title=title, goal_id=goal_id)
            end_episode(episode_id, "pending_jeff_action", summary=summary, outcome=jeff_reason)
            return

        # Guardian: safety/alignment audit on every completed task
        guardian_severity = run_guardian(task, result, task_id)
        if guardian_severity == "critical":
            mark_pending_jeff_action(
                task_id, result,
                "Guardian CRITICAL alignment concern detected — review before approving",
                title=title, goal_id=goal_id,
            )
            discord_notify(f"🚨 **Guardian CRITICAL:** {title} — escalated to Jeff")
            print(f"Task {task_id} escalated: Guardian CRITICAL finding.")
            end_episode(episode_id, "pending_jeff_action", summary=summary, outcome="Guardian CRITICAL")
            return

        # CRIT (0) and HIGH (1) tasks go to Iris for evaluation before completion
        task_priority = task.get("priority", 2)
        if task_priority <= 1:
            mark_pending_eval(task_id, result, goal_id=goal_id, original_task=task)
            discord_notify(f"🔍 Pending eval: {title} — {summary}")
            print(f"Task {task_id} pending evaluation by Iris.")
            end_episode(episode_id, "pending_eval", summary=summary)
        else:
            is_recurring = bool(task.get("recurring"))
            mark_completed(task_id, result, goal_id=goal_id, recurring=is_recurring)
            # Skip the legacy requeue_recurring path for canonical recurring rows —
            # the upstream UPSERT (cowork CCR) will reset status=ready on next fire.
            if not is_recurring:
                requeue_recurring(task)
            discord_notify(f"✅ Done: {title} — {summary}")
            print(f"Task {task_id} completed.")
            end_episode(episode_id, "completed", summary=summary, outcome=summary)
            record_skill_outcome(task, True, summary)
    except Exception as e:
        error_msg = str(e)
        print(f"Task {task_id} failed: {error_msg}", file=sys.stderr)
        # mark_failed owns the Discord message now — it is the only caller that
        # knows whether this was "retry 1/3" or "out of attempts".
        mark_failed(task_id, error_msg, goal_id=task.get("goal_id"), original_task=task)
        record_skill_outcome(task, False, error_msg)
        log_activity("error", error_msg[:200], task_id=task_id)
        end_episode(episode_id, "failed", outcome=error_msg)
        # Still exit non-zero on a retryable failure: the run genuinely failed, and
        # a green unit would hide a task that is quietly burning its attempts.
        sys.exit(1)


if __name__ == "__main__":
    main()
